// Interface text in Bahasa Malaysia, keyed by the English text it replaces.
// Anything without an entry falls back to English, so a missing key never breaks the page.
// {name} marks a value filled in at run time. Have a native speaker review before a public launch.

export const toLang = (value: unknown): Lang => (value === "ms" ? "ms" : "en");

export function tr(lang: Lang, text: string, vars?: Record<string, string | number>): string {
  const out = (lang === "ms" && MS[text]) || text;
  return vars ? out.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole)) : out;
}

